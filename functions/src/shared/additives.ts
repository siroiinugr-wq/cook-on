// 添加物の見分けと、ラベルでの書き方（食品表示基準）。
// 添加物は原材料と分けて「／」のあとに重い順で書く。書き方は3つ：
//  ① 一括名：同じ目的の物質をまとめた名前で書いてよいもの（膨脹剤・香料・乳化剤・酸味料・pH調整剤・かんすい・イーストフードなど）。
//     膨脹剤は「膨張剤」「ベーキングパウダー」「ふくらし粉」と書いても同じ扱い（どれも正式な一括名）
//  ② 用途名併記：何のために使ったかと物質名を両方書くもの（甘味料・着色料・保存料・増粘剤・ゲル化剤・酸化防止剤など）→「ゲル化剤（ペクチン）」
//  ③ 物質名だけ（トレハロースなど）
// 名前から見分けられるものだけ。見分けられないものは材料の編集で「添加物」に印を付ける。

export interface AdditiveRule {
  /** 材料の名前（NFKC・小文字にしたもの）に当てる */
  match: RegExp;
  /** ラベルに書ける名前。先頭が「おすすめ」（短く、正式なもの） */
  options: string[];
  /** 画面に出すひとこと */
  note: string;
}

