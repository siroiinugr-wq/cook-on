const norm = (s: string) => s.normalize("NFKC").toLowerCase().replace(/\s+/g, "");

/** 名前から添加物かどうかを見分ける。見分けられなければ null */
export function guessAdditive(name: string): AdditiveRule | null {
  const s = norm(name);
  if (!s) return null;
  // 「ベーキングパウダー入りの〇〇ミックス」のような既製品は添加物そのものではない
  if (/ミックス|の素$/.test(s)) return null;
  return ADDITIVE_RULES.find((r) => r.match.test(s) && r.options.length > 0) ?? null;
}

/** ラベルでの添加物の名前：材料に覚えた名前（labelName）が正式な書き方ならそれ、無ければおすすめ（先頭） */
export function additiveLabel(name: string, labelName?: string): string | null {
  const rule = guessAdditive(labelName || name) ?? guessAdditive(name);
  if (!rule) return null;
  if (labelName && rule.options.includes(labelName)) return labelName;
  return rule.options[0];
}
